import 'dart:convert';
import 'dart:io';
import 'package:archive/archive.dart';
import 'package:flutter/material.dart';
import '../models/theme_project.dart';

class ThemeExportService {
  static String generateThemeToml(ThemeProject p) {
    final primary = toHex(p.primary);
    final onPrimary = toHex(p.onPrimary);
    final secondary = toHex(p.secondary);
    final surface = toHex(p.surface);
    final surfaceDim = adjustBrightness(p.surface, -0.15);
    final surfaceBright = adjustBrightness(p.surface, 0.20);
    final containerLowest = adjustBrightness(p.surface, 0.05);
    final containerLow = adjustBrightness(p.surface, 0.10);
    final container = adjustBrightness(p.surface, 0.15);
    final containerHigh = adjustBrightness(p.surface, 0.20);
    final containerHighest = adjustBrightness(p.surface, 0.25);
    final onSurface = toHex(p.onSurface);
    final keyboardSurface = toHex(p.keyboardSurface);
    final keyboardContainer = toHex(p.keyboardContainer);
    final keyboardPress = toHex(p.keyboardPress);

    return '''# Generated by FUTO Theme Studio
name = "${p.name}"
author = "${p.author}"
id = "${p.id}"
version = 1
description = "${p.description}"

[options]
auto_borders = true
center_hints = false
roundedness = ${p.roundedness.toStringAsFixed(2)}
scale_text = ${p.scaleText.toStringAsFixed(2)}
scale_hints = ${p.scaleHints.toStringAsFixed(2)}
weight_text = 400
weight_hints = 400

[colors]
primary = "$primary"
on_primary = "$onPrimary"
primary_container = "$primary"
on_primary_container = "$surface"
inverse_primary = "$secondary"
secondary = "$secondary"
on_secondary = "#FFFFFFFF"
secondary_container = "$containerHigh"
on_secondary_container = "$onSurface"
tertiary = "$secondary"
on_tertiary = "#FFFFFFFF"
tertiary_container = "$containerHigh"
on_tertiary_container = "$onSurface"
background = "$surface"
on_background = "$onSurface"
surface = "$surface"
surface_dim = "$surfaceDim"
surface_bright = "$surfaceBright"
surface_container_lowest = "$containerLowest"
surface_container_low = "$containerLow"
surface_container = "$container"
surface_container_high = "$containerHigh"
surface_container_highest = "$containerHighest"
on_surface = "$onSurface"
surface_variant = "$container"
on_surface_variant = "$onSurface"
surface_tint = "$primary"
inverse_surface = "$onSurface"
inverse_on_surface = "$surface"
error = "#C00100FF"
on_error = "#FFFFFFFF"
error_container = "#FFDAD4FF"
on_error_container = "#2A1613FF"
outline = "#327D9DFF"
outline_variant = "#327D9DFF"
scrim = "#000000FF"

keyboard_surface = "$keyboardSurface"
keyboard_surface_dim = "$surfaceDim"
keyboard_container = "$keyboardContainer"
keyboard_container_variant = "$containerHigh"
on_keyboard_container = "$onSurface"
keyboard_press = "$keyboardPress"
keyboard_container_pressed = "$containerHighest"
on_keyboard_container_pressed = "$onSurface"

[[matchrules.border]]
selector = "normal"
asset = "Button-default.png"

[[matchrules.border]]
selector = "functional"
asset = "Button-function.png"

[[matchrules.border]]
selector = "spacebar"
asset = "Button-space.png"

[[matchrules.icon]]
selector = "icon delete_key"
asset = "Icon-backspace.png"

[[matchrules.icon]]
selector = "icon enter_key"
asset = "Icon-enter.png"

[[asset.border]]
