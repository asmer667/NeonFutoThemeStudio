background_tint = "$keyboardContainer"
foreground_tint = "$onSurface"
padding = [0.0, 0.0, 0.0, 0.0]
slicing = [16.0, 16.0, 16.0, 16.0]
gap = [2, 2, 2, 2]
target_density = 640

[[asset.border]]
name = "Button-function.png"
background_tint = "$containerHigh"
foreground_tint = "$onSurface"
padding = [0.0, 0.0, 0.0, 0.0]
slicing = [16.0, 16.0, 16.0, 16.0]
gap = [2, 2, 2, 2]
target_density = 640

[[asset.border]]
name = "Button-space.png"
background_tint = "$keyboardPress"
foreground_tint = "$onSurface"
padding = [0.0, 0.0, 0.0, 0.0]
slicing = [16.0, 16.0, 16.0, 16.0]
gap = [2, 2, 2, 2]
target_density = 640

[[asset.icon]]
name = "Icon-backspace.png"
target_density = 640

[[asset.icon]]
name = "Icon-enter.png"
target_density = 640
''';
  }

  static String toHex(Color color) {
    final r = (color.r * 255).round();
    final g = (color.g * 255).round();
    final b = (color.b * 255).round();
    final a = (color.a * 255).round();
    return '#${r.toRadixString(16).padLeft(2, '0')}'
            '${g.toRadixString(16).padLeft(2, '0')}'
            '${b.toRadixString(16).padLeft(2, '0')}'
            '${a.toRadixString(16).padLeft(2, '0')}'
        .toUpperCase();
  }

  static String adjustBrightness(Color color, double factor) {
    final hsl = HSLColor.fromColor(color);
    final newLightness = (hsl.lightness + factor).clamp(0.0, 1.0);
    return toHex(hsl.withLightness(newLightness).toColor());
  }

  static Future<File> exportThemeZip(
    ThemeProject project,
    List<File> assets,
    Directory outputDir,
  ) async {
    final archive = Archive();

    final themeToml = generateThemeToml(project);
    final themeBytes = utf8.encode(themeToml);
    archive.addFile(ArchiveFile('theme.txt', themeBytes.length, themeBytes));

    final readme = 'FUTO Theme: ${project.name}\n'
        'Author: ${project.author}\n'
        'ID: ${project.id}\n';
    final readmeBytes = utf8.encode(readme);
    archive.addFile(ArchiveFile('README.txt', readmeBytes.length, readmeBytes));

    for (final asset in assets) {
      if (await asset.exists()) {
        final bytes = await asset.readAsBytes();
        archive.addFile(ArchiveFile(asset.uri.pathSegments.last, bytes.length, bytes));
      }
    }

    final zipBytes = ZipEncoder().encode(archive)!;
    final outputFile = File(
      '${outputDir.path}/${project.name.replaceAll(' ', '_')}.zip',
    );
    await outputFile.writeAsBytes(zipBytes);
    return outputFile;
  }
}
