import 'dart:convert';
import 'dart:typed_data';
import 'package:archive/archive.dart';
import 'package:flutter/services.dart' show rootBundle;
import '../models/theme_project.dart';

class ThemeExportService {
  String _tomlString(String value) =>
      '"${value.replaceAll(r'\', r'\\').replaceAll('"', r'\"').replaceAll('\n', r'\n')}"';

  String _hex(ThemeProject p, dynamic color) {
    // FUTO theme colors use #RRGGBBAA; Flutter Color.value is AARRGGBB.
    final value = color.value as int;
    final rgb = value.toRadixString(16).padLeft(8, '0').toUpperCase();
    return '"#${rgb.substring(2)}${rgb.substring(0, 2)}"';
  }

  String generateThemeTxt(ThemeProject p) {
    final b = StringBuffer()
      ..writeln('# Generated by Ultimate Theme Creator Studio')
      ..writeln('# Validate this package with FUTO Keyboard before publishing.')
      ..writeln('name = ${_tomlString(p.name)}')
      ..writeln('author = ${_tomlString(p.author)}')
      ..writeln('id = ${_tomlString('studio.${p.id.replaceAll('-', '')}')} ')
      ..writeln('version = ${p.version}')
      ..writeln('description = ${_tomlString(p.description)}')
      ..writeln()
      ..writeln('[options]')
      ..writeln('auto_borders = true')
      ..writeln('center_hints = false')
      ..writeln('roundedness = ${(p.radius / 12).clamp(0.0, 2.0).toStringAsFixed(2)}')
      ..writeln('scale_text = ${p.keyScale.toStringAsFixed(2)}')
      ..writeln('scale_hints = 0.90')
      ..writeln('weight_text = 400')
      ..writeln('weight_hints = 400')
      ..writeln()
      ..writeln('[colors]');
    final colors = <String, dynamic>{
      'primary': p.primary,
      'on_primary': p.keyText,
      'primary_container': p.primary,
      'on_primary_container': p.background,
      'inverse_primary': p.secondary,
      'secondary': p.secondary,
      'on_secondary': p.keyText,
      'secondary_container': p.functionKey,
      'on_secondary_container': p.keyText,
      'tertiary': p.secondary,
      'on_tertiary': p.keyText,
      'tertiary_container': p.functionKey,
      'on_tertiary_container': p.keyText,
      'background': p.background,
      'on_background': p.keyText,
      'surface': p.background,
      'on_surface': p.keyText,
      'surface_variant': p.keyColor,
      'on_surface_variant': p.keyText,
      'surface_tint': p.primary,
      'inverse_surface': p.keyText,
      'inverse_on_surface': p.background,
      'error': const _FixedColor(0xFFC00100),
      'on_error': const _FixedColor(0xFFFFFFFF),
      'error_container': const _FixedColor(0xFFFFDAD4),
      'on_error_container': const _FixedColor(0xFF2A1613),
      'outline': p.outline,
      'outline_variant': p.outline,
      'scrim': const _FixedColor(0xFF000000),
    };
    for (final entry in colors.entries) {
      b.writeln('${entry.key} = ${_hex(p, entry.value)}');
    }
    // Conservative border rules point only to assets that are emitted below.
    b
      ..writeln()
      ..writeln('[[matchrules.border]]')
      ..writeln('selector = "normal"')
      ..writeln('asset = "Button-default.png"')
      ..writeln()
      ..writeln('[[matchrules.border]]')
      ..writeln('selector = "functional"')
      ..writeln('asset = "Button-function.png"')
      ..writeln()
      ..writeln('[[matchrules.border]]')
      ..writeln('selector = "spacebar"')
      ..writeln('asset = "Button-space.png"')
      ..writeln()
      ..writeln('[[matchrules.icon]]')
      ..writeln('selector = "icon delete_key"')
      ..writeln('asset = "Icon-backspace.png"')
      ..writeln()
      ..writeln('[[matchrules.icon]]')
      ..writeln('selector = "icon enter_key"')
      ..writeln('asset = "Icon-enter.png"')
      ..writeln()
      ..writeln('[[asset.border]]')
      ..writeln('name = "Button-default.png"')
      ..writeln('background_tint = ${_hex(p, p.keyColor)}')
      ..writeln('foreground_tint = ${_hex(p, p.keyText)}')
      ..writeln('padding = [0.0, 0.0, 0.0, 0.0]')
      ..writeln('slicing = [16.0, 16.0, 16.0, 16.0]')
      ..writeln('gap = [2, 2, 2, 2]')
      ..writeln('target_density = 640')
      ..writeln()
      ..writeln('[[asset.border]]')
      ..writeln('name = "Button-function.png"')
      ..writeln('background_tint = ${_hex(p, p.functionKey)}')
      ..writeln('foreground_tint = ${_hex(p, p.keyText)}')
      ..writeln('padding = [0.0, 0.0, 0.0, 0.0]')
      ..writeln('slicing = [16.0, 16.0, 16.0, 16.0]')
      ..writeln('gap = [2, 2, 2, 2]')
      ..writeln('target_density = 640')
      ..writeln()
      ..writeln('[[asset.border]]')
      ..writeln('name = "Button-space.png"')
      ..writeln('background_tint = ${_hex(p, p.primary)}')
      ..writeln('foreground_tint = ${_hex(p, p.keyText)}')
      ..writeln('padding = [0.0, 0.0, 0.0, 0.0]')
      ..writeln('slicing = [16.0, 16.0, 16.0, 16.0]')
      ..writeln('gap = [2, 2, 2, 2]')
      ..writeln('target_density = 640')
      ..writeln()
      ..writeln('[[asset.icon]]')
      ..writeln('name = "Icon-backspace.png"')
      ..writeln('target_density = 640')
      ..writeln()
      ..writeln('[[asset.icon]]')
      ..writeln('name = "Icon-enter.png"')
      ..writeln('target_density = 640');
    return b.toString();
  }

  Future<Uint8List> createZip(ThemeProject p, {Map<String, List<int>>? assets}) async {
    final archive = Archive();
    final themeBytes = utf8.encode(generateThemeTxt(p));
    archive.addFile(ArchiveFile('theme.txt', themeBytes.length, themeBytes));
    final readme = utf8.encode(
      '# ${p.name}\n\nCreated with Ultimate Theme Creator Studio.\n\n'
      'Import this ZIP into FUTO Keyboard advanced themes and verify its appearance.\n',
    );
    archive.addFile(ArchiveFile('README.md', readme.length, readme));
    const license = 'User-provided or generated assets retain their respective licenses. Replace this file with the appropriate license notices before distribution.\n';
    final licenseBytes = utf8.encode(license);
    archive.addFile(ArchiveFile('LICENSE.txt', licenseBytes.length, licenseBytes));
    // Bundle the supplied working Pet Keys theme assets as starter assets.
    // The spacebar asset is renamed to the canonical Button-space.png reference
    // used by this generator.
    final bundledAssets = <String, String>{
      'Button-default.png': 'assets/sample_theme/Button-default.png',
      'Button-function.png': 'assets/sample_theme/Button-function.png',
      'Button-space.png': 'assets/sample_theme/Button-space-dark.png',
      'Icon-backspace.png': 'assets/sample_theme/Icon-backspace.png',
      'Icon-enter.png': 'assets/sample_theme/Icon-enter.png',
    };
    for (final entry in bundledAssets.entries) {
      try {
        final data = await rootBundle.load(entry.value);
        final bytes = data.buffer.asUint8List(data.offsetInBytes, data.lengthInBytes);
        archive.addFile(ArchiveFile(entry.key, bytes.length, bytes));
      } catch (_) {
        // Missing starter assets are caught by the package validation checklist.
      }
    }
    if (assets != null) {
      for (final entry in assets.entries) {
        archive.addFile(ArchiveFile(entry.key, entry.value.length, entry.value));
      }
    }
    final encoded = ZipEncoder().encode(archive);
    if (encoded == null) throw StateError('ZIP encoder returned no data');
    return Uint8List.fromList(encoded);
  }
}

class _FixedColor {
  const _FixedColor(this.value);
  final int value;
}
